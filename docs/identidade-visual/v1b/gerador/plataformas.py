"""V2 (round 23, decision 259): the identity's platform files for vgr-app.

Writes, into a vgr-app checkout, everything the phone and the browser show
before Flutter draws its first frame:

- Android: adaptive icon (navy background, white arc and gold dot in the
  safe zone), themed icon (Android 13+), legacy icons, the opening screen
  for light and dark, before and after Android 12 (vector drawables, so no
  density buckets);
- iOS: the app icon set, the launch image and background for light and dark;
- web (mobile and panel): favicon, icons, maskable icons.

Run from this folder, with the fonts fetched and Chromium + playwright at
hand (they draw the PNGs from the same SVGs as the V1b files):

    python3 -B plataformas.py /path/to/vgr-app
"""
import base64, json, math, os, subprocess, sys, tempfile
from PIL import Image

from mark import (BBOX, SOFT, CX, CY, DOT_R, DOT_DY, arc_path, symbol_svg, icon_svg,
                  ADAPTIVE, FULL)
from tokens import TOKENS, MARK

HERE = os.path.dirname(os.path.abspath(__file__))

def _f(v):
    return f'{v:.3f}'.rstrip('0').rstrip('.')

def _argb(hex6):
    return '#FF' + hex6.lstrip('#').upper()

# ---------------------------------------------------------------- Android vectors
def _vector(width_dp, height_dp, vw, vh, s, tx, ty, arc, dot, comment):
    """The symbol (100-unit geometry) as an Android VectorDrawable."""
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by vgr-ai/docs/identidade-visual/v1b/gerador/plataformas.py — do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{_f(width_dp)}dp"
    android:height="{_f(height_dp)}dp"
    android:viewportWidth="{_f(vw)}"
    android:viewportHeight="{_f(vh)}">
    <group
        android:translateX="{_f(tx)}"
        android:translateY="{_f(ty)}"
        android:scaleX="{_f(s)}"
        android:scaleY="{_f(s)}">
        <path
            android:fillColor="{_argb(arc)}"
            android:strokeColor="{_argb(arc)}"
            android:strokeWidth="{SOFT}"
            android:strokeLineJoin="round"
            android:pathData="{arc_path()}" />
        <path
            android:fillColor="{_argb(dot)}"
            android:pathData="M{_f(CX - DOT_R)},{_f(CY + DOT_DY)}a{DOT_R},{DOT_R} 0 1,0 {_f(2 * DOT_R)},0a{DOT_R},{DOT_R} 0 1,0 {_f(-2 * DOT_R)},0z" />
    </group>
</vector>
'''

def _centred(canvas, sym_width):
    """Scale and translation that centre the symbol's box, `sym_width` wide."""
    x0, y0, x1, y1 = BBOX
    s = sym_width / (x1 - x0)
    return s, canvas / 2 - (x0 + x1) / 2 * s, canvas / 2 - (y0 + y1) / 2 * s

def android(app):
    res = os.path.join(app, 'android', 'app', 'src', 'main', 'res')
    files = {}
    # Adaptive icon: 108-unit canvas, symbol inside the 66-unit safe circle.
    s, tx, ty = _centred(108, 108 * ADAPTIVE)
    files['drawable/ic_launcher_foreground.xml'] = _vector(
        108, 108, 108, 108, s, tx, ty, MARK['white'], MARK['gold'],
        'Adaptive icon, foreground: the symbol on the navy background (decision 261).')
    files['drawable/ic_launcher_monochrome.xml'] = _vector(
        108, 108, 108, 108, s, tx, ty, '#FFFFFF', '#FFFFFF',
        'Themed icon (Android 13+): one colour, tinted by the system.')
    files['mipmap-anydpi-v26/ic_launcher.xml'] = '''<?xml version="1.0" encoding="utf-8"?>
<!-- The VGR icon (decisions 252, 261): navy, white arc, gold dot — nothing that says "report". -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
    # Opening screen before Android 12: a layer list with the symbol 120 dp wide.
    x0, y0, x1, y1 = BBOX
    w, h = x1 - x0, y1 - y0
    for folder, mode, arc in (('drawable', 'light', MARK['white']), ('drawable-night', 'dark', TOKENS['dark']['brand'])):
        files[f'{folder}/splash_symbol.xml'] = _vector(
            120, 120 * h / w, w, h, 1, -x0, -y0, arc, MARK['gold'],
            f'Opening screen symbol, {mode} (decision 256).')
    # Android 12+: the system splash; icon canvas 288 dp, content within a 192 dp circle.
    half_diag = math.hypot(w / 2, h / 2)
    sym_w = 0.9 * 96 / half_diag * w
    s, tx, ty = _centred(288, sym_w)
    for folder, mode, arc in (('drawable', 'light', MARK['white']), ('drawable-night', 'dark', TOKENS['dark']['brand'])):
        files[f'{folder}/splash_icon.xml'] = _vector(
            288, 288, 288, 288, s, tx, ty, arc, MARK['gold'],
            f'Android 12+ opening screen icon, {mode} (decision 256).')
    layer = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Opening screen (decision 256): navy in light, near-black in dark (values-night). -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background" />
    <item
        android:drawable="@drawable/splash_symbol"
        android:gravity="center" />
</layer-list>
'''
    files['drawable/launch_background.xml'] = layer
    files['drawable-v21/launch_background.xml'] = layer
    files['values/colors.xml'] = f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- The VGR identity (round 24); source: vgr-ai/docs/identidade-visual/v1b/gerador/tokens.py -->
    <color name="ic_launcher_background">{MARK['navy']}</color>
    <color name="splash_background">{TOKENS['light']['splash']}</color>
</resources>
'''
    files['values-night/colors.xml'] = f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Dark opening screen: draws less attention at night (decision 256). -->
    <color name="splash_background">{TOKENS['dark']['splash']}</color>
</resources>
'''
    for folder, parent in (('values-v31', 'Theme.Light.NoTitleBar'), ('values-night-v31', 'Theme.Black.NoTitleBar')):
        files[f'{folder}/styles.xml'] = f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Android 12+ draws its own opening screen: the VGR background and symbol (decision 256). -->
    <style name="LaunchTheme" parent="@android:style/{parent}">
        <item name="android:windowBackground">@drawable/launch_background</item>
        <item name="android:windowSplashScreenBackground">@color/splash_background</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_icon</item>
    </style>
    <style name="NormalTheme" parent="@android:style/{parent}">
        <item name="android:windowBackground">?android:colorBackground</item>
    </style>
</resources>
'''
    for rel, text in files.items():
        path = os.path.join(res, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w') as fh:
            fh.write(text)
    # Legacy launcher icons (before Android 8): the rounded icon.
    jobs = [(icon_svg('square', standalone=True, uid=f'm{px}'), os.path.join(res, f'mipmap-{d}', 'ic_launcher.png'), px, True)
            for d, px in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192))]
    return sorted(files), jobs

# ---------------------------------------------------------------- iOS
def ios(app):
    xc = os.path.join(app, 'ios', 'Runner', 'Assets.xcassets')
    jobs = []
    full = icon_svg('none', standalone=True, uid='ios')
    with open(os.path.join(xc, 'AppIcon.appiconset', 'Contents.json')) as fh:
        contents = json.load(fh)
    for image in contents['images']:
        pts = float(image['size'].split('x')[0])
        scale = int(image['scale'].rstrip('x'))
        jobs.append((full, os.path.join(xc, 'AppIcon.appiconset', image['filename']), round(pts * scale), False))
    # Launch image: the symbol 120 pt wide, white arc in light, blue in dark.
    x0, y0, x1, y1 = BBOX
    li = os.path.join(xc, 'LaunchImage.imageset')
    images = []
    for mode, arc, suffix in (('light', MARK['white'], ''), ('dark', TOKENS['dark']['brand'], 'Dark')):
        svg = symbol_svg(arc, MARK['gold'], standalone=True, pad=0)
        for scale in (1, 2, 3):
            name = f'LaunchImage{suffix}{"" if scale == 1 else f"@{scale}x"}.png'
            jobs.append((svg, os.path.join(li, name), (round(120 * scale), round(120 * scale * (y1 - y0) / (x1 - x0))), True))
            entry = {'idiom': 'universal', 'filename': name, 'scale': f'{scale}x'}
            if mode == 'dark':
                entry['appearances'] = [{'appearance': 'luminosity', 'value': 'dark'}]
            images.append(entry)
    with open(os.path.join(li, 'Contents.json'), 'w') as fh:
        json.dump({'images': images, 'info': {'version': 1, 'author': 'xcode'}}, fh, indent=2)
        fh.write('\n')
    # Launch background: one pixel per appearance, stretched by the storyboard.
    bg = os.path.join(xc, 'LaunchBackground.imageset')
    os.makedirs(bg, exist_ok=True)
    for name, color in (('background.png', TOKENS['light']['splash']), ('darkbackground.png', TOKENS['dark']['splash'])):
        Image.new('RGB', (1, 1), color).save(os.path.join(bg, name))
    with open(os.path.join(bg, 'Contents.json'), 'w') as fh:
        json.dump({'images': [
            {'filename': 'background.png', 'idiom': 'universal'},
            {'appearances': [{'appearance': 'luminosity', 'value': 'dark'}], 'filename': 'darkbackground.png', 'idiom': 'universal'},
        ], 'info': {'version': 1, 'author': 'xcode'}}, fh, indent=2)
        fh.write('\n')
    return jobs

# ---------------------------------------------------------------- web
def web(app_web):
    rounded = icon_svg('square', standalone=True, uid='w')
    full = icon_svg('none', standalone=True, uid='wm')
    favicon = icon_svg('favicon', standalone=True, uid='wf')
    with open(os.path.join(app_web, 'favicon.svg'), 'w') as fh:
        fh.write(favicon + '\n')
    return [
        (favicon, os.path.join(app_web, 'favicon.png'), 32, True),
        (rounded, os.path.join(app_web, 'icons', 'Icon-192.png'), 192, True),
        (rounded, os.path.join(app_web, 'icons', 'Icon-512.png'), 512, True),
        (full, os.path.join(app_web, 'icons', 'Icon-maskable-192.png'), 192, False),
        (full, os.path.join(app_web, 'icons', 'Icon-maskable-512.png'), 512, False),
    ]

# ---------------------------------------------------------------- raster
def raster(jobs):
    """Draws each SVG to a PNG of the exact size with Chromium."""
    spec = []
    for svg, out, size, transparent in jobs:
        w, h = size if isinstance(size, tuple) else (size, size)
        spec.append({'svg': base64.b64encode(svg.encode()).decode(), 'out': out, 'w': w, 'h': h, 'transparent': transparent})
    with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as fh:
        json.dump(spec, fh)
    subprocess.run(['node', os.path.join(HERE, 'raster.js'), fh.name], check=True)
    os.unlink(fh.name)
    for item in spec:
        im = Image.open(item['out'])
        # iOS rejects app icons with an alpha channel; maskable icons are full bleed too.
        im = im.convert('RGBA' if item['transparent'] else 'RGB')
        im.save(item['out'], optimize=True)

def main(app_root):
    mobile = os.path.join(app_root, 'apps', 'mobile')
    admin = os.path.join(app_root, 'apps', 'admin')
    written, jobs = android(mobile)
    jobs += ios(mobile)
    jobs += web(os.path.join(mobile, 'web'))
    jobs += web(os.path.join(admin, 'web'))
    raster(jobs)
    print('android resources:', ', '.join(written))
    print('pngs:', len(jobs))

if __name__ == '__main__':
    main(sys.argv[1])
